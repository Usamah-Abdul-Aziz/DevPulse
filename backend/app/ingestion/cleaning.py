"""Cleaning rules: bot accounts and generated/vendored files (blueprint §6.1).

These filters are the data-ethics-relevant part of ingestion (AGENTS.md: bots and generated files
are *flagged*, never deleted — the filters stay auditable). Every rule is spelled out here rather
than scattered through the loaders, so a reviewer can audit exactly what gets excluded.
"""

from __future__ import annotations

import re

#: Bot accounts excluded from contributor and workload metrics.
#: The `[bot]` suffix is the generic pattern (all GitHub Apps carry it); the list catches the
#: well-known ones that predate the convention and a few that are easy to miss.
BOT_LOGINS: frozenset[str] = frozenset(
    {
        "dependabot",
        "dependabot-preview",
        "renovate",
        "renovate-bot",
        "github-actions",
        "actions-user",
        "pyup-bot",
        "pre-commit-ci",
        "mergify",
        "imgbot",
        "greenkeeper",
        "greenkeeperio-bot",
        "sonarsource",
        "sonarcloud",
        "semantic-release-bot",
        "codecov",
        "codecov-io",
        "coveralls",
        "netlify",
        "vercel",
        "files-sync-bot",
    }
)

_BOT_SUFFIX = re.compile(r"\[bot\]$")


def is_bot_login(login: str | None) -> bool:
    """True for GitHub App / bot accounts, which are excluded from people metrics."""
    if not login:
        return False
    if _BOT_SUFFIX.search(login):
        return True
    return login.lower() in BOT_LOGINS


#: Generated or vendored paths excluded from churn and PR-size metrics.
#: Matches against the POSIX path (forward slashes), case-insensitively.
GENERATED_PATH_PATTERNS: tuple[re.Pattern[str], ...] = tuple(
    re.compile(pattern, re.IGNORECASE)
    for pattern in (
        # Lockfiles — machine-generated, enormous churn, zero analytic signal.
        r"(^|/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|poetry\.lock|"
        r"cargo\.lock|composer\.lock|gemfile\.lock|pipfile\.lock|go\.sum|go\.mod\.sum)$",
        r"(^|/).*\.lock$",
        # JS/TS build output and vendored bundles.
        r"(^|/)(dist|build|out|bundle|\.next|\.nuxt|node_modules|bower_components|vendor|"
        r"third_party|external)/",
        r"(^|/).*\.min\.(js|css|map)$",
        r"(^|/).*\.(d\.ts|js\.map|css\.map)$",
        # Test snapshots and coverage artifacts.
        r"(^|/)(__snapshots__|__fixtures__|coverage|\.nyc_output)/",
        r"(^|/).*\.snap$",
        # Generated code, by convention.
        r"(^|/).*\.generated\.(js|ts|py|go|rs|java|cs)$",
        r"(^|/)(generated|autogenerated|gen)/",
        r"(^|/).*\.(pb\.go|pb\.rs|pb\.java)$",  # protobuf stubs
        r"(^|/).*_pb2\.py$",
        # GitHub / CI metadata that inflates churn without reflecting human work.
        r"(^|/)\.github/workflows/",
    )
)


def is_generated_path(path: str | None) -> bool:
    """True if a path is generated or vendored, so it is excluded from size/churn metrics."""
    if not path:
        return False
    return any(pattern.search(path) for pattern in GENERATED_PATH_PATTERNS)
